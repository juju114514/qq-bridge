"""从已登录的调试浏览器导出抖音 cookies（Netscape 格式），给 yt-dlp / 桥接解析器用。

为什么需要：抖音的分享页解析和 yt-dlp 都要登录态；桥接里那份 cookies.txt 会过期
（现场那次是 10 月 30 日导的，11 月 13 日就报「需要登录态」）。
调试浏览器（9237 端口，profile <DY_PROFILE 目录>）里是活的登录态，
所以直接从页面取一遍、写成 Netscape 文件。

用法：
  python export_cookies.py --out "state/cookies/site-cookies.txt"
  python export_cookies.py --check      # 只看有几个 cookie、最早什么时候过期
"""
import argparse
import asyncio
import json
import os
import time
import urllib.request

import websockets

PORT = 9237
DOUYIN_URLS = [
    "https://www.douyin.com/",
    "https://www.douyin.com/video/7700660682928967397",
    "https://v.douyin.com/",
    "https://www.iesdouyin.com/",
]


def http_json(url, timeout=6):
    with urllib.request.urlopen(url, timeout=timeout) as r:
        return json.loads(r.read().decode())


async def _send(ws, mid, method, params=None):
    await ws.send(json.dumps({"id": mid, "method": method, "params": params or {}}))
    while True:
        m = json.loads(await ws.recv())
        if m.get("id") == mid:
            return m


async def get_cookies(target_url, urls=None):
    async with websockets.connect(target_url, max_size=2 ** 25) as ws:
        r = await _send(ws, 1, "Network.getCookies", {"urls": urls or DOUYIN_URLS})
        res = (r.get("result") or {}).get("cookies") or []
        return res


def to_netscape(cookies):
    lines = ["# Netscape HTTP Cookie File", "# generated by export_cookies.py", ""]
    seen = set()
    for c in cookies:
        name = str(c.get("name") or "")
        value = str(c.get("value") or "")
        domain = str(c.get("domain") or "")
        if not name or not domain:
            continue
        key = (name, domain)
        if key in seen:
            continue
        seen.add(key)
        path = c.get("path") or "/"
        secure = "TRUE" if c.get("secure") else "FALSE"
        expires = c.get("expires")
        if isinstance(expires, (int, float)) and expires and expires > 0:
            exp = int(expires)
        else:
            exp = str(int(time.time()) + 86400 * 180)      # 会话 cookie 给个保守有效期
        # domain 以点开头表示包含子域
        sub = "TRUE" if domain.startswith(".") else "FALSE"
        lines.append("\t".join([domain, sub, path, secure, str(exp), name, value]))
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=PORT)
    ap.add_argument("--urls", default="", help="逗号分隔的 URL 列表；默认是抖音那几条（导出 pixiv 时传 https://www.pixiv.net/）")
    ap.add_argument("--out", default=os.environ.get("QQB_COOKIES") or os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "state", "cookies", "site-cookies.txt"))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    port = int(args.port)
    pages = [x for x in http_json(f"http://127.0.0.1:{port}/json/list") if x.get("type") == "page"]
    if not pages:
        print("[失败] 调试浏览器没有可用页面")
        return
    target = next((p for p in pages if "douyin.com" in (p.get("url") or "")), pages[0])
    _urls = [u.strip() for u in (args.urls or "").split(",") if u.strip()] or None
    cookies = asyncio.run(get_cookies(target["webSocketDebuggerUrl"], _urls))
    print(f"[取到] {len(cookies)} 个 cookie（页面：{(target.get('url') or '')[:40]}）")

    if args.check:
        now = time.time()
        soon = [c for c in cookies if isinstance(c.get("expires"), (int, float)) and 0 < c["expires"] - now < 86400]
        print(f"  24 小时内过期: {len(soon)} 个")
        for name in ("sessionid", "sessionid_ss", "ttwid", "odin_tt", "passport_csrf_token"):
            hit = next((c for c in cookies if c.get("name") == name), None)
            print(f"  {name}: " + ("有" if hit else "无"))
        return

    text = to_netscape(cookies)
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"[写盘] {args.out}（{len(text)} 字节，{text.count(chr(10))} 行）")


if __name__ == "__main__":
    main()
